#!/usr/bin/env node
// Regenerates js/sounds.js from assets/sounds/*.wav so the metronome samples
// are embedded in the page and work when index.html is opened from disk.
// Usage: node tools/embed-sounds.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const files = {
  high: 'high.wav',
  low: 'low.wav',
  digitalHigh: 'digital-high.wav',
  digitalLow: 'digital-low.wav',
};

let out = '/* Generated by tools/embed-sounds.js — do not edit by hand. */\n';
out += 'window.FS = window.FS || {};\nwindow.FS.SOUNDS = {\n';
for (const [key, file] of Object.entries(files)) {
  const b64 = fs.readFileSync(path.join(root, 'assets', 'sounds', file)).toString('base64');
  out += `  ${key}: '${b64}',\n`;
}
out += '};\n';
fs.writeFileSync(path.join(root, 'js', 'sounds.js'), out);
console.log('Wrote js/sounds.js (' + out.length + ' bytes)');
